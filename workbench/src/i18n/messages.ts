export const messages: Record<"zh" | "en", { [K in MessageKey]: string }> = { zh, en };

const messageKeys = new Set<string>(Object.keys(zh));

export function isMessageKey(key: string): key is MessageKey {
  return messageKeys.has(key);
}

export type Translate = (key: MessageKey, vars?: Record<string, string | number>) => string;

export function translateId(t: Translate, prefix: "error" | "check" | "status", id: string): string | null {
  const key = `${prefix}.${id}`;
  if (!isMessageKey(key)) {
    return null;
  }
  return t(key);
}

export function labelText(t: Translate, key: string): string {
  if (!isMessageKey(key)) {
    return key;
  }
  return t(key);
}

/** Translate a known status token. Unknown API values stay as returned. */
export function statusText(t: Translate, value: string): string {
  return translateId(t, "status", value) ?? value;
}
